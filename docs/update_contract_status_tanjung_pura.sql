-- Normalize to KLIP's two representations; drop any unknown status safely.
CREATE TEMP TABLE _po_map ON COMMIT DROP AS
SELECT DISTINCT
  btrim(po_number) AS po_number,
  CASE lower(btrim(excel_status))
    WHEN 'open' THEN 'Open'
    WHEN 'closed' THEN 'Close'
    WHEN 'close' THEN 'Close'
    WHEN 'batal' THEN 'Cancelled'
    WHEN 'cancelled' THEN 'Cancelled'
    WHEN 'canceled' THEN 'Cancelled'
  END AS spd_status,
  CASE lower(btrim(excel_status))
    WHEN 'open' THEN 'ACTIVE'
    WHEN 'closed' THEN 'COMPLETED'
    WHEN 'close' THEN 'COMPLETED'
    WHEN 'batal' THEN 'CANCELLED'
    WHEN 'cancelled' THEN 'CANCELLED'
    WHEN 'canceled' THEN 'CANCELLED'
  END AS contract_status
FROM _po_status
WHERE btrim(coalesce(po_number,'')) <> '';

DELETE FROM _po_map WHERE spd_status IS NULL;  -- drop unmapped statuses

-- ---------- PREVIEW (pre-update) ----------
\echo '--- Match summary (POs in file vs DB) ---'
SELECT
  (SELECT count(*) FROM _po_map)                                                                              AS pos_in_file,
  (SELECT count(*) FROM _po_map m WHERE EXISTS (SELECT 1 FROM contracts c          WHERE c.po_number = m.po_number)) AS matched_in_contracts,
  (SELECT count(*) FROM _po_map m WHERE EXISTS (SELECT 1 FROM sap_processed_data s WHERE s.po_number = m.po_number)) AS matched_in_sap_processed,
  (SELECT count(*) FROM _po_map m WHERE NOT EXISTS (SELECT 1 FROM contracts c      WHERE c.po_number = m.po_number)) AS not_found_in_contracts;

\echo '--- POs in file but NOT in contracts (will NOT be updated) ---'
SELECT m.po_number, m.spd_status
FROM _po_map m
WHERE NOT EXISTS (SELECT 1 FROM contracts c WHERE c.po_number = m.po_number)
ORDER BY 1;

\echo '--- Sample of changes that will be applied (current -> new) ---'
SELECT c.po_number,
       c.status AS contracts_now, m.contract_status AS contracts_new,
       (SELECT s.data->'contract'->>'status' FROM sap_processed_data s
          WHERE s.po_number = c.po_number ORDER BY s.created_at DESC NULLS LAST LIMIT 1) AS sap_now,
       m.spd_status AS sap_new
FROM contracts c JOIN _po_map m ON m.po_number = c.po_number
WHERE c.status IS DISTINCT FROM m.contract_status
ORDER BY c.po_number
LIMIT 50;

-- ---------- APPLY ----------
-- (1) contracts.status
UPDATE contracts c
SET status = m.contract_status,
    updated_at = CURRENT_TIMESTAMP
FROM _po_map m
WHERE c.po_number = m.po_number
  AND c.status IS DISTINCT FROM m.contract_status;

-- (2) sap_processed_data.data->'contract'->>'status'  (priority display source)
UPDATE sap_processed_data s
SET data = jsonb_set(
             CASE WHEN s.data ? 'contract' THEN s.data
                  ELSE jsonb_set(s.data, '{contract}', '{}'::jsonb, true) END,
             '{contract,status}', to_jsonb(m.spd_status::text), true),
    updated_at = CURRENT_TIMESTAMP
FROM _po_map m
WHERE s.po_number = m.po_number
  AND COALESCE(s.data->'contract'->>'status','') IS DISTINCT FROM m.spd_status;

-- ---------- POST-UPDATE VERIFICATION ----------
\echo '--- Rows now matching target status (contracts) ---'
SELECT count(*) AS contracts_at_target
FROM contracts c JOIN _po_map m ON m.po_number = c.po_number
WHERE c.status = m.contract_status;

